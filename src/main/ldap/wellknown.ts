export function resolveWellKnownSid(sid: string, domainSID?: string): string | undefined {
  if (WELL_KNOWN_SIDS[sid]) return WELL_KNOWN_SIDS[sid]
  if (domainSID && sid.startsWith(domainSID + '-')) {
    const rid = Number(sid.slice(domainSID.length + 1))
    if (DOMAIN_RIDS[rid]) return DOMAIN_RIDS[rid]
  }
  return undefined
}

